def eval_traj_ll_vector(
    model, 
    traj_path, 
    num_acc=10, 
    step_size=0.001, 
    device=None
):
    """
    Compute a vector of log-likelihoods at each time-step for one trajectory.

    Args:
        model: Flow network, already on `device` and in eval() mode.
        traj_path (str): Path to one .npz file with keys 'state','action'.
        num_acc (int): Number of Hutchinson repetitions.
        step_size (float): ODE solver step size.
        device: torch device (default cuda if available).

    Returns:
        ll_vec (np.ndarray of shape (T,)): mean log-likelihood per time-step.
    """
    device = device or torch.device("cuda" if torch.cuda.is_available() else "cpu")
    wrapped = ModelWrapper(model)
    solver  = ODESolver(velocity_model=wrapped)

    # --- load one trajectory ---
    data   = np.load(traj_path)
    states = torch.from_numpy(data['state']).to(device)    # (T, S)
    actions= torch.from_numpy(data['action']).to(device)   # (T, A)
    x1     = torch.cat([states, actions], dim=-1)          # (T, D)
    D      = x1.shape[-1]

    # base density for CNF likelihood
    base_dist = Independent(Normal(
        torch.zeros(D, device=device),
        torch.ones(D,  device=device)
    ), 1).log_prob

    # accumulate per-step LLm
    ll_acc = torch.zeros(x1.size(0), device=device)  # (T,)
    with torch.no_grad():
        for _ in range(num_acc):
            # sample random initial point and times
            x0 = torch.randn_like(x1)
            t  = torch.rand(x1.size(0), device=device)
            # compute vector of log-likelihoods at each time-step
            _, ll = solver.compute_likelihood(
                x_1            = x1,
                method         = 'midpoint',
                step_size      = step_size,
                exact_divergence = False,
                log_p0         = base_dist
            )
            ll_acc += ll  # ll has shape (T,)
    ll_vec = (ll_acc / num_acc).cpu().numpy()  # average over Hutchinson

    return ll_vec

