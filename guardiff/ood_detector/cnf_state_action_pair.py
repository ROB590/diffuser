class Flow(nn.Module):
    def __init__(self, dim, hidden_dim=2048):  #hidden_dim=600
        """
        Args:
            dim (int): Dimensionality of the input (observation + flattened actions).
            hidden_dim (int): Number of hidden units.
        """
        super(Flow, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(dim + 1, hidden_dim), nn.ELU(),
            nn.Linear(hidden_dim, hidden_dim), nn.ELU(),
            nn.Linear(hidden_dim, hidden_dim), nn.ELU(),
            nn.Linear(hidden_dim, dim)
        )
    
    def forward(self, x, t):
        # x: (..., T, D), t: (T,) or (batch, T) or (...)
        # ensure t has same leading dims as x, then one trailing dim
        # desired shape for t: x.shape[:-1] + [1]
        target_shape = list(x.shape[:-1]) + [1]             # e.g. [batch, T, 1]
        
        # first, make t a tensor
        if not torch.is_tensor(t):
            t = torch.tensor(t, device=x.device)
        
        # unsqueeze up to rank-1
        while t.dim() < x.dim() - 1:
            t = t.unsqueeze(0)                             # prepend dims
        # now t.dim() == x.dim()-1; e.g. t is [batch, T] or [T]
        
        # add the final time-dim
        t = t.unsqueeze(-1)                                # [..., T, 1]
        
        # expand to match x’s batch/time dims
        t = t.expand(*target_shape)
        
        # concat time channel in front of features
        xt = torch.cat([t, x], dim=-1)                     # [..., T, D+1]
        return self.net(xt)

class DiffuserTrajectoryDataset(Dataset):
    """
    Loads .npz episodes generated by the Diffuser rollout logger.
    split: 'succ', 'fail', or None for both.
    """
    def __init__(self, root_dir, split=None, transform=None):
        pattern = '*_succ.npz' if split=='succ' else '*_fail.npz' if split=='fail' else '*.npz'
        self.files = sorted(glob.glob(os.path.join(root_dir, pattern)))
        if not self.files:
            raise RuntimeError(f"No .npz files found in {root_dir} with split={split}")
        self.transform = transform

        # Peek at first file to get dims
        sample = np.load(self.files[0])
        self.state_dim  = sample['state'].shape[1]
        self.action_dim = sample['action'].shape[1]

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        data = np.load(self.files[idx])
        # shape (T, D)
        states     = torch.from_numpy(data['state'])      # (T, state_dim)
        actions    = torch.from_numpy(data['action'])     # (T, action_dim)
        next_states= torch.from_numpy(data['next_state']) # (T, state_dim)
        # optionally you could also return rewards, dones
        sample = {
            'state':      states,
            'action':     actions,
            'next_state': next_states,
        }
        if self.transform:
            sample = self.transform(sample)
        return sample

    def dims(self):
        return self.state_dim, self.action_dim


def train(use_action=False,traj_root = "/home/haoran-zhang/Desktop/projects/guardiff/trajectories"):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Training on device: {device}")
    dataset    = DiffuserTrajectoryDataset(traj_root, split='succ')
    state_dim, action_dim = dataset.dims()
    D = state_dim + action_dim
    # Initialize the CNF model with the proper input dimension.
    model = Flow(dim=D).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=1e-4)
    dataloader = DataLoader(dataset, batch_size=128, shuffle=True, num_workers=4, collate_fn=lambda x: x)
    # collate_fn=lambda x: x keeps the episode dimension (list of samples), you can flatten later

    path  = AffineProbPath(scheduler=CondOTScheduler())
    num_epochs = 3000

    for epoch in range(num_epochs):
        epoch_loss = 0.0
        pbar = tqdm(dataloader, desc=f"Epoch {epoch+1}/{num_epochs}")
        for batch in pbar:
            # batch is a list of samples (each with sequences of length T)
            # flatten across time: we want (B*T, D) tensors for x0,x1
            states     = torch.cat([s['state']     for s in batch], dim=0).to(device)  # (sum T, state_dim)
            actions    = torch.cat([s['action']    for s in batch], dim=0).to(device)  # (sum T, action_dim)
            next_states= torch.cat([s['next_state']for s in batch], dim=0).to(device)

            x1 = torch.cat([states, actions], dim=-1)  # (N, D)
            x0 = torch.randn_like(x1)                  # (N, D)
            t  = torch.rand(x1.size(0), device=device)

            path_sample = path.sample(t=t, x_0=x0, x_1=x1)
            loss = (model(path_sample.x_t, path_sample.t) - path_sample.dx_t).pow(2).mean()

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            epoch_loss += loss.item()
            pbar.set_postfix(loss=f"{loss.item():.4f}")

        print(f"Epoch {epoch+1}, Avg Loss: {epoch_loss/len(dataloader):.4f}")

        # save periodic checkpoints
        if (epoch+1) % 200 == 0:
            torch.save(model.state_dict(), f"checkpoint_epoch_{epoch+1}.pth")

    return model



