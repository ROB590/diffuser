import glob, os
import numpy as np
import torch
from torch.utils.data import Dataset

class DiffuserTrajectoryDataset(Dataset):
    """
    Loads .npz episodes generated by the Diffuser rollout logger.
    split: 'succ', 'fail', or None for both.
    """
    def __init__(self, root_dir, split=None, transform=None):
        pattern = '*_succ.npz' if split=='succ' else '*_fail.npz' if split=='fail' else '*.npz'
        self.files = sorted(glob.glob(os.path.join(root_dir, pattern)))
        self.transform = transform

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        data = np.load(self.files[idx])
        sample = {
            'state':      torch.from_numpy(data['state']),       # (T,4)
            'action':     torch.from_numpy(data['action']),      # (T,2)
            'next_state': torch.from_numpy(data['next_state']),  # (T,4)
            'reward':     torch.from_numpy(data['reward']),      # (T,)
            'done':       torch.from_numpy(data['done'].astype(np.float32))  # (T,)
        }
        # label for classification (optional)
        label = 1.0 if '_succ.npz' in self.files[idx] else 0.0
        sample['label'] = torch.tensor(label, dtype=torch.float32)
        if self.transform:
            sample = self.transform(sample)
        return sample
    def dims(self):
        return self.state_dim, self.action_dim

